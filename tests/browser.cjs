// Run with ARCHIVIST_TEST_TOKEN_FILE pointing to a private file; never commit credentials.
const {chromium}=require('playwright');
const fs=require('node:fs');
(async()=>{
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:1280,height:900}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(process.env.ARCHIVIST_TEST_URL||'http://127.0.0.1:18098');
 await page.getByLabel('Chave de acesso individual').fill(fs.readFileSync(process.env.ARCHIVIST_TEST_TOKEN_FILE,'utf8').trim());
 await page.getByRole('button',{name:'Entrar no acervo'}).click();
 await page.locator('#workspace').waitFor({state:'visible'});
 await page.locator('.card').first().waitFor();
 const existingName=await page.locator('.card strong').first().textContent();
 await page.getByRole('button',{name:'Importar imagens',exact:true}).click();
 await page.getByLabel('Arquivos PNG, JPEG ou WebP').fill(existingName);
 await page.getByLabel('Confirmo que a cópia terminou.').check();
 await page.getByRole('button',{name:'Importar',exact:true}).click();
 await page.locator('#import-dialog').waitFor({state:'hidden'});
 await page.waitForFunction(()=>document.querySelector('#status').textContent.includes('registradas'));
 await page.getByLabel('O que você procura?').fill('uma imagem azul');
 await page.getByRole('button',{name:'Buscar',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('.card strong')?.textContent.includes('blue'));
 await page.screenshot({path:process.env.ARCHIVIST_SCREENSHOT||'/tmp/archivist-desktop.png',fullPage:true});
 await page.locator('.card').first().click();
 await page.locator('#detail-dialog').waitFor({state:'visible'});
 await page.locator('#detail-image').evaluate(img=>{if(!img.complete||!img.naturalWidth)throw new Error('Preview did not load');});
 const downloadEvent=page.waitForEvent('download');
 await page.getByRole('button',{name:'Baixar original'}).click();
 const download=await downloadEvent;
 if(!download.suggestedFilename().endsWith('.png'))throw new Error('Invalid download filename');
 await page.getByRole('button',{name:'Fechar',exact:true}).click();
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:'/tmp/archivist-mobile.png',fullPage:true});
 if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw new Error('Horizontal overflow');
 await page.getByRole('button',{name:'Sair',exact:true}).click();
 await page.locator('#login').waitFor({state:'visible'});
 if(errors.length)throw new Error(errors.join('\n'));
 await browser.close();
 console.log('PASS: login, hybrid search, preview, download, mobile layout and logout; no JS errors.');
})().catch(e=>{console.error(e);process.exit(1)});
