const {chromium}=require('playwright');
(async()=>{
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:1280,height:900}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(process.env.ARCHIVIST_TEST_URL||'http://127.0.0.1:18098');
 if(await page.locator('input[type=password]').count())throw new Error('Unexpected login');
 await page.locator('#workspace').waitFor({state:'visible'});
 await page.locator('.card').first().waitFor();
 const existingName=await page.locator('.card[data-mime^="image/"]').first().getAttribute('data-name');
 await page.getByRole('button',{name:'Importar arquivos',exact:true}).click();
 await page.getByLabel('Arquivos MP4, MOV, M4V, PNG, JPEG ou WebP').fill(existingName);
 await page.getByLabel('Confirmo que a cópia terminou.').check();
 await page.getByRole('button',{name:'Importar',exact:true}).click();
 await page.locator('#import-dialog').waitFor({state:'hidden'});
 await page.waitForFunction(()=>document.querySelector('#status').textContent.includes('registrados'));
 await page.getByLabel('O que você procura?').fill('uma imagem azul');
 await page.getByRole('button',{name:'Buscar',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('.card strong')?.textContent.includes('blue'));
 await page.screenshot({path:process.env.ARCHIVIST_SCREENSHOT||'/tmp/archivist-desktop.png',fullPage:true});
 await page.locator('.card').first().click();
 await page.locator('#detail-dialog').waitFor({state:'visible'});
 await page.locator('#detail-image').evaluate(img=>{if(!img.complete||!img.naturalWidth)throw new Error('Preview did not load');});
 const downloadEvent=page.waitForEvent('download');
 await page.getByRole('button',{name:'Baixar original'}).click();
 const download=await downloadEvent;
 if(!download.suggestedFilename().endsWith('.png'))throw new Error('Invalid download filename');
 await page.getByRole('button',{name:'Fechar',exact:true}).click();
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:'/tmp/archivist-mobile.png',fullPage:true});
 if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw new Error('Horizontal overflow');
 if(errors.length)throw new Error(errors.join('\n'));
 await browser.close();
 console.log('PASS: direct access, import, hybrid search, preview, download, mobile layout; no JS errors.');
})().catch(e=>{console.error(e);process.exit(1)});
